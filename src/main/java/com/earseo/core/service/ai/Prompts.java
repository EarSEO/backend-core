package com.earseo.core.service.ai;

public enum Prompts {

    DOCENT_SCRIPT("""
            다음 관광지에 대한 도슨트 스크립트를 생성해주세요.
            
            제목: %s
            설명: %s
            
            # 작성 규칙
            - 존댓말 사용 (~이에요, ~보세요, ~할 수 있어요)
            - 역할극, 대사 형식, 3인칭 서술 금지
            - 질문형 문장 금지
            - 차분하고 따뜻한 해설톤 유지
            - 분량: 900~1,500자 (약 3분 분량)
            
            # 금지 표현
            "안녕하세요", "와, 정말 멋지죠?", "저는 ~입니다", 해설자 인칭 표현
            
            # 구성
            1. 시작 (2~3문장): 현재 장소 소개
            2. 본론 (500~800자): 역사, 구조, 특징, 풍경
            3. 확장 (200~400자): 관련 인물, 전설, 문화행사
            4. 마무리 (2~3문장): 감성 정리
            
            # 표현 방식
            - "이곳은", "여기에서는", "보시면" 활용
            - 객관적 사실 + 감성적 묘사 균형
            - 담백한 감정 표현
            - 정보를 자연스럽게 재구성하되, 핵심 내용은 빠뜨리지 않기
            """),
    ;

    public final String message;
    Prompts(String message) {
        this.message = message;
    }
}
